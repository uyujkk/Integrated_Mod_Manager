/// <summary>
/// One feature in the search's feature directory: what it is called, where it is in the window, other words it is
/// found by and its shortcut. Picking it goes to <see cref="Section"/>, makes the page ready (<see cref="Prepare"/>),
/// opens <see cref="Container"/> when the place is folded inside it, and points at <see cref="Target"/> (an x:Name or an
/// automation id). Without a target the location text is the guide, for places that need a selection first.
/// </summary>
internal sealed record FeatureEntry(string Id, int Area, PrimarySection? Section, string Glyph, string Title, string Where,
    string Words, string? Target, string? Container, string Shortcut, string? Prepare, bool Wide = false)
{
    public CommandPaletteEntry ToPaletteEntry() => new(CommandPaletteKind.Feature, Title, Where, "feature:" + Id, Words, Shortcut, Area);
}

